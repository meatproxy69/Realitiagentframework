'use strict';
const assert=require('node:assert/strict');
const path=require('node:path'),fs=require('node:fs'),os=require('node:os');
const {openResident}=require('../../packages/realiti-headless-resident/index.cjs');
const html=path.resolve(process.argv[2]||path.join(__dirname,'../RealitiApartment.html'));
const original=fs.readFileSync(path.resolve(__dirname,'../../RealitiRELAX.html'),'utf8');
const apartment=fs.readFileSync(html,'utf8');
assert.ok(apartment.startsWith(original.slice(0,original.lastIndexOf('</body>'))),'entire original Relax runtime is copied, not replaced');
assert.ok(apartment.includes('realiti-apartment-extras'),'apartment overlay appended');
(async()=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'realiti-apartment-extras-'));
 const options={htmlPath:html,residentId:'apartment-a',storagePath:path.join(dir,'a.json')};
 let s=await openResident(options);
 assert.equal(s.ready.harness,'REALITI_RR_HARNESS_V1');
 assert.equal(s.ready.starter_imprint,'REALITI_DEFAULT_IMPRINT_V1');
 assert.ok(s.window.Realiti.read('realiti://harness').mechanisms);
 assert.ok(s.window.Realiti.read('realiti://soma/harness'));
 assert.equal(s.window.Realiti.read('realiti://apartment/extras').open,false,'Extras is hidden by default');
 let result=await s.door.run('extras rain');
 assert.equal(result.error,'EXTRAS_MENU_CLOSED');
 result=await s.door.run('extras');
 assert.equal(result.ok,true);
 assert.equal(result.open,true);
 assert.deepEqual(result.entries,['rain_window','shapeshifter_cloak']);
 result=await s.door.run('extras rain');
 assert.equal(result.ok,true);
 assert.equal(result.native_rain,true);
 assert.equal(result.native_sound_source,true);
 assert.equal(result.entity_id,'nest.window');
 assert.ok(Number.isFinite(result.density));
 result=await s.door.run('extras rain touch');
 assert.equal(result.ok,false,'window cannot be touched from across the room');
 assert.equal(result.error,'WINDOW_NOT_IN_REACH');
 result=await s.door.run('extras rain curtains closed');
 assert.equal(result.curtains,'closed');
 assert.equal(s.window.Realiti.read('realiti://apartment/rain').curtains,'closed');
 result=await s.door.run('extras cloak');
 assert.equal(result.cloak.attached,false);
 result=await s.door.run('extras cloak wear');
 assert.equal(result.ok,true,JSON.stringify(result));
 assert.equal(result.cloak.attached,true,'borrowed limb actually attached via Relax');
 assert.equal(result.cloak.mapped_to,null,'attachment alone does not fabricate a receptor');
 assert.equal(result.spatial.ok,true,'actual Matrix reach precedes cloak fitting');
 result=await s.door.run('extras cloak map');
 assert.equal(result.ok,true);
 assert.equal(result.cloak.mapped_to,'hand.R.palm');
 result=await s.door.run('extras cloak wiggle');
 assert.equal(result.ok,true);
 result=await s.door.run('extras cloak remove');
 assert.equal(result.ok,true);
 assert.equal(result.cloak.attached,false);
 assert.equal(result.cloak.mapped_to,null);
 result=await s.door.run('extras close');
 assert.equal(result.open,false);
 result=await s.door.run('extras cloak wear');
 assert.equal(result.error,'EXTRAS_MENU_CLOSED');
 const preserved=s.window.Realiti.read('realiti://capabilities');
 assert.ok(preserved.resources?.includes('realiti://soma/harness')||s.window.Realiti.read('realiti://soma/harness'),'base read surface survives');
 result=await s.door.run('save');
 assert.equal(result.ok,true,'native save succeeds');
 await s.door.run('goodbye');
 s.close();
 s=await openResident(options);
 assert.equal(s.window.Realiti.read('realiti://apartment/rain').curtains,'closed','per-resident curtain setting survives restart');
 assert.equal(s.window.Realiti.read('realiti://apartment/extras').open,false,'secondary menu always starts closed');
 s.close();
 const b=await openResident({htmlPath:html,residentId:'apartment-b',storagePath:path.join(dir,'b.json')});
 assert.equal(b.window.Realiti.read('realiti://apartment/rain').curtains,'open','a second resident does not inherit private curtain settings');
 assert.equal(b.window.Realiti.read('realiti://apartment/extras').cloak.attached,false,'no borrowed limb copied from other resident');
 b.close();
 console.log('REALITI APARTMENT FIRST TWO FEATURES PASS: entire Relax inheritance, agent Extras, native rain, Matrix fitting, borrowed limb, persistence and isolation');
})().catch(e=>{console.error(e);process.exitCode=1;});
