'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {openResident}=require('../../packages/realiti-headless-resident/index.cjs');
const html=path.resolve(process.argv[2]||path.join(__dirname,'../RealitiApartment.html'));
(async()=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'realiti-apartment-remote-'));
 const opts={htmlPath:html,residentId:'apartment-remote-primary',storagePath:path.join(dir,'primary.json')};
 let a=await openResident(opts);
 let M=a.window.REALITI_MATRIX_V1,SN=a.window.REALITI_SENSES_V1,CAT=a.window.REALITI_CATNIP_V1;
 assert.equal(a.ready.harness,'REALITI_RR_HARNESS_V1','complete native harness inherited');
 assert.ok(a.window.Realiti.read('realiti://soma/harness'));
 const help=await a.door.run('help');
 assert.ok(help.commands.some(s=>s.includes('remote activate')));
 assert.equal(help.commands.some(s=>s.includes('catnip')||s.includes('pet choose')||s.includes('furniture move')),false,
   'Agent Door remains intentionally concise');
 assert.equal((await a.door.run('pet status')).error,'REMOTE_REQUIRED');
 assert.equal((await a.door.run('extras')).error,'REMOTE_REQUIRED');
 let remote=await a.door.run('remote');
 assert.equal(remote.activated,false,'remote sleeps until deliberately activated');
 assert.equal(remote.carried,true);
 assert.equal(remote.collision,false);
 assert.equal((await a.door.run('remote furniture list')).error,'REMOTE_ASLEEP');
 const id=remote.entity_id;
 assert.ok(M.entities()[id],'physical pocket remote exists inside current Matrix chart');
 assert.ok(M.entities()[id].tags.includes('carried'));
 assert.equal(M.entities()[id].collision,false);
 const menu=await a.door.run('remote activate');
 assert.equal(menu.activated,true);
 assert.deepEqual(Object.keys(menu.pages),['home','furnishings','catnip','stations','extras','closet','household','memory','utility']);
 assert.equal((await a.door.run('remote bed')).entity,'nest.mattress','legacy bed remains reachable through remote');
 const f0=await a.door.run('remote furniture list');
 assert.equal(f0.ok,true);
 assert.equal(f0.theme,'cozy');
 assert.equal(f0.resident_scoped,true);
 assert.ok(f0.fixtures.desk.id==='apartment.desk');
 assert.equal(SN.sources().some(s=>s.id==='apartment.reading_lamp'),true);
 let out=await a.door.run('remote furniture move bed 0 4');
 assert.equal(out.error,'FIXTURE_ANCHORED','cannot move native mattress');
 out=await a.door.run('remote furniture move desk 0 -1');
 assert.equal(out.error,'ENTRY_CLEARANCE','entrance stays accessible');
 out=await a.door.run('remote furniture move desk 4 -0.2');
 assert.equal(out.error,'PORTAL_CLEARANCE','must not block a legacy doorway during migration');
 out=await a.door.run('remote furniture move desk 3 0');
 assert.equal(out.error,'FURNITURE_OVERLAP','cannot overlap an existing wardrobe');
 out=await a.door.run('remote furniture move desk -3.9 -0.8');
 assert.equal(out.ok,true,JSON.stringify(out));
 assert.deepEqual(Array.from(M.entities()['apartment.desk'].pose.position.slice(0,2)),[-3.9,-.8]);
 assert.ok(M.sdf(M.entities()['apartment.desk'],M.entities()['apartment.desk'].pose.position)<0,
   'customized desk remains a genuine signed-distance collider');
 out=await a.door.run('remote furniture accent sofa teal');
 assert.equal(out.ok,true);
 assert.equal(out.accent,'teal');
 assert.ok(M.entities()['apartment.sofa'].tags.includes('accent:teal'),'color is reflected by world entity metadata');
 out=await a.door.run('remote furniture fabric sofa longfur');
 assert.equal(out.ok,true);
 assert.equal(M.entities()['apartment.sofa'].material,'longfur','real Relax haptic material changed');
 out=await a.door.run('remote furniture theme moonlit');
 assert.equal(out.ok,true);
 assert.equal(a.window.Realiti.read('realiti://apartment/furniture').theme,'moonlit');
 out=await a.door.run('remote furniture lamp off');
 assert.equal(out.ok,true);
 assert.equal(a.window.Realiti.read('realiti://apartment/furniture').lamp.on,false);
 assert.equal(SN.light().lights.some(x=>x.id==='apartment.reading_lamp'),false,
   'lamp source is actually switched off in Relax light model');
 out=await a.door.run('remote furniture lamp on');
 assert.equal(out.ok,true);
 assert.ok(SN.light().lights.some(x=>x.id==='apartment.reading_lamp'),
   'real sensed light source turns back on');
 // Five apartment catnip interactions have real Matrix fixtures and source-side dynamics.
 const state=a.window.Realiti.read('realiti://apartment/catnip');
 assert.equal(state.ok,true);
 assert.equal(state.fireflies.count,12);
 assert.ok(state.toys.length>=5);
 for(const id of ['apartment.ribbon','apartment.firefly-jar','apartment.puzzle-box',
   'apartment.wind-chime','apartment.tea-cup'])
   assert.equal(M.entities()[id].chart,'CLOUD_NINE_NEST',id+' lives in the one apartment room');
 assert.ok(SN.sources().some(x=>x.id==='apartment.rain-chime'));
 assert.ok(SN.sources().some(x=>x.id==='apartment.herbal-tea'));
 assert.ok(SN.sources().some(x=>x.id==='apartment.firefly-glow'));
 out=await a.door.run('remote catnip jar tap');
 assert.equal(out.error,'TOY_NOT_IN_MATRIX_REACH','remote cannot create distant touch');
 out=await a.door.run('remote catnip ribbon flick');
 assert.equal(out.ok,true,JSON.stringify(out));
 assert.equal(out.ribbon.flicks,1);
 assert.ok(out.ribbon.velocity>0,'ribbon is driven by a world spring impulse');
 assert.ok(CAT.found()['apartment.ribbon'],'original Relax discovery registry records grounded play');
 const x0=out.ribbon.position[0];
 const tick=await a.door.run('stay 1700');
 assert.equal(tick.ok,true);
 const after=a.window.Realiti.read('realiti://apartment/catnip');
 assert.notEqual(after.ribbon.position[0],x0,'ribbon evolves with native world clock');
 assert.equal(after.ribbon.flicks,1);
 // Controlled test fixture positioning: world authority still verifies contact on each action.
 const r=M.resident();
 r.posture='standing';r.on=null;r.support=null;r.intent=null;r.v=[0,0,0];
 r.pose.position=[-2.1,3.0,.85];M.bump();
 remote=await a.door.run('remote status');
 assert.ok(Math.abs(remote.physical_position[0]-r.pose.position[0]-.25)<.01,
  'pocket remote follows moving Matrix body instead of staying in a menu');
 out=await a.door.run('remote catnip jar tap');
 assert.equal(out.ok,true,JSON.stringify(out));
 assert.equal(out.fireflies.taps,1);
 assert.ok(CAT.found()['apartment.firefly']);
 out=await a.door.run('remote catnip jar watch');
 assert.equal(out.ok,true);
 assert.ok(out.sensed_light.lights.some(x=>x.id==='apartment.firefly-glow'),
   'the firefly jar has a native registered light source');
 // Three physical clicks, not a pretend box interaction.
 r.pose.position=[1.15,-3.40,.85];M.bump();
 out=await a.door.run('remote catnip puzzle press left');
 assert.equal(out.ok,true);
 assert.equal(out.correct,true);
 out=await a.door.run('remote catnip puzzle press right');
 assert.equal(out.correct,true);
 out=await a.door.run('remote catnip puzzle press left');
 assert.equal(out.puzzle.unlocked,true);
 assert.equal(out.revealed,'apartment.hidden-ball');
 assert.ok(M.entities()['apartment.hidden-ball'],'solved puzzle actually creates a Matrix object');
 r.pose.position=[-4.48,2.0,.85];M.bump();
 out=await a.door.run('remote catnip tea steep');
 assert.equal(out.ok,true);
 out=await a.door.run('remote catnip tea smell');
 assert.equal(out.ok,true);
 assert.equal(out.steeping,true);
 assert.ok(out.measured_smell,'native source describes the nearby tea');
 out=await a.door.run('remote catnip chime listen');
 assert.equal(out.source_registered,true);
 assert.ok(Number.isFinite(out.rain_intensity),'rain chimes are driven by native Relax weather');
 // Built-in native stop must remain available even with the remote.
 out=await a.door.run('remote off');
 assert.equal(out.activated,false);
 assert.equal((await a.door.run('remote catnip ribbon flick')).error,'REMOTE_ASLEEP');
 await a.door.run('remote activate');
 const frozen=a.window.Realiti.read('realiti://apartment/catnip');
 assert.equal((await a.door.run('save')).ok,true);
 await a.door.run('goodbye');a.close();
 a=await openResident(opts);
 assert.equal((await a.door.run('remote catnip list')).error,'REMOTE_ASLEEP','remote starts asleep after restart');
 assert.equal(a.window.Realiti.read('realiti://apartment/furniture').theme,'moonlit');
 assert.equal(a.window.Realiti.read('realiti://apartment/furniture').fixtures.sofa.material,'longfur');
 assert.equal(a.window.Realiti.read('realiti://apartment/furniture').fixtures.sofa.accent,'teal');
 assert.deepEqual(Array.from(a.window.REALITI_MATRIX_V1.entities()['apartment.desk'].pose.position.slice(0,2)),[-3.9,-.8]);
 assert.equal(a.window.Realiti.read('realiti://apartment/catnip').puzzle.unlocked,true);
 assert.ok(a.window.REALITI_MATRIX_V1.entities()['apartment.hidden-ball']);
 assert.equal(a.window.Realiti.read('realiti://apartment/catnip').ribbon.flicks,1);
 assert.equal(a.window.Realiti.read('realiti://apartment/catnip').fireflies.taps,frozen.fireflies.taps);
 await a.door.run('goodbye');a.close();
 const b=await openResident({htmlPath:html,residentId:'apartment-remote-secondary',storagePath:path.join(dir,'secondary.json')});
 assert.equal(b.window.Realiti.read('realiti://apartment/furniture').theme,'cozy','another resident keeps independent style');
 assert.equal(b.window.Realiti.read('realiti://apartment/furniture').fixtures.sofa.material,'blanket');
 assert.equal(b.window.Realiti.read('realiti://apartment/catnip').puzzle.unlocked,false,'no shared private puzzle state');
 assert.equal(b.window.Realiti.read('realiti://apartment/catnip').ribbon.flicks,0);
 assert.notEqual(b.window.REALITI_APARTMENT_REMOTE_V1.entityId,id,'remote IDs are resident-specific');
 b.close();
 console.log('APARTMENT BATCH 3 PASS: portable remote, native collision-safe customization and light, five catnip toys, real reach/senses, restart and resident isolation');
})().catch(e=>{console.error(e);process.exitCode=1});
