'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),vm=require('node:vm');
const dir=path.resolve(__dirname,'../visual/dist');
const bytes=fs.readFileSync(path.join(dir,'viewer.js'));
const m=JSON.parse(fs.readFileSync(path.join(dir,'manifest.json'),'utf8'));
assert.equal(m.schema,'REALITI_LOCAL_THREE_VIEWER_V0');
assert.equal(m.version,'0.187.0');
assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'),m.sha256);
assert.equal(bytes.length,m.bytes);
assert.equal(m.external_cdns,0);
assert.equal(m.reference_views,4);
const text=bytes.toString('utf8');
assert.match(text,/const REVISION = '187';/);
assert.doesNotMatch(text,/from '\\.\/three\\.core\\.js'|from 'three'|https:\/\/cdn\./);
const sandbox={window:{},document:undefined,console};
vm.runInNewContext(text,sandbox,{timeout:10000,filename:'viewer.js'});
assert.deepEqual(Array.from(sandbox.window.REALITI_APARTMENT_THREE_V0.referenceIds),['NE','NW','SW','SE']);
console.log('Offline bundled Three.js r187: hash, evaluation and cameras PASS');
